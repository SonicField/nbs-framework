#define ARRAY_LEN(a) ((int)(sizeof(a) / sizeof((a)[0])))

int nbs_ts_wcwidth(uint32_t cp) {
    /* C0/C1 control characters */
    if (cp < 0x20) return -1;
    if (cp >= 0x7F && cp < 0xA0) return -1;

    /* Zero-width */
    if (in_ranges(cp, zero_width, ARRAY_LEN(zero_width)))
        return 0;

    /* Double-width */
    if (in_ranges(cp, double_width, ARRAY_LEN(double_width)))
        return 2;

    /* Default: normal width */
    return 1;
}
