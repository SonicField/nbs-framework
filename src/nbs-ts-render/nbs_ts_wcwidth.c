/*
 * nbs_ts_wcwidth.c — Bundled Unicode character width table.
 *
 * Based on Unicode 15.1 East Asian Width and General Category data.
 * Uses binary search over sorted codepoint ranges.
 *
 * No locale dependency. No external libraries.
 */

#include "nbs_ts_wcwidth.h"

struct cp_range {
    uint32_t lo;
    uint32_t hi;
};

static int in_ranges(uint32_t cp, const struct cp_range *ranges, int count) {
    int lo = 0, hi = count - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (cp < ranges[mid].lo) hi = mid - 1;
        else if (cp > ranges[mid].hi) lo = mid + 1;
        else return 1;
    }
    return 0;
}

